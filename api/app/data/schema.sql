-- KPE database schema. Loaded by the api on first start (bootstrap stage 1).
-- :EMBED_DIM is replaced with the configured embedding dimension.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE app_bootstrap (
    stage       text PRIMARY KEY,
    done_at     timestamptz NOT NULL DEFAULT now(),
    info        jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE users (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role            text NOT NULL,              -- customer | staff
    staff_title     text,                       -- manager | seller | mechanic
    full_name       text NOT NULL,
    national_id          text NOT NULL,
    phone           text NOT NULL,
    email           text NOT NULL UNIQUE,
    password_hash   text,
    province       text,
    canton          text,
    district        text,
    address_details           text,
    created_at      timestamptz NOT NULL
);

CREATE TABLE inventory_vehicles (
    id                  text PRIMARY KEY,
    plate               text NOT NULL,
    brand               text NOT NULL,
    model               text NOT NULL,
    year                integer NOT NULL,
    km                  integer NOT NULL,
    fuel                text NOT NULL,
    transmission        text NOT NULL,
    body                text NOT NULL,
    color               text NOT NULL,
    price               integer NOT NULL,
    cost                integer NOT NULL,
    status              text NOT NULL,          -- available | reserved | sold
    published           boolean NOT NULL,
    description         text NOT NULL,
    inspection_summary  text NOT NULL,
    inspection_status   text NOT NULL,          -- excellent | acceptable | needs_repairs
    created_at          timestamptz NOT NULL
);

CREATE TABLE customer_vehicles (
    plate           text PRIMARY KEY,
    owner_user_id   integer NOT NULL REFERENCES users(id),
    brand           text NOT NULL,
    model           text NOT NULL,
    year            integer NOT NULL
);

CREATE TABLE service_records (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate               text NOT NULL,
    service_date        date NOT NULL,
    km                  integer NOT NULL,
    mechanic_user_id    integer REFERENCES users(id),
    notes               text NOT NULL
);
CREATE INDEX service_records_plate_idx ON service_records (plate);

CREATE TABLE bulletins (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            text NOT NULL,
    title           text NOT NULL,
    body_md         text NOT NULL,
    published_at    date NOT NULL
);

CREATE TABLE faq_documents (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page        text NOT NULL,
    position    integer NOT NULL,
    title       text NOT NULL,
    body_md     text NOT NULL
);

CREATE TABLE internal_policies (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        text NOT NULL UNIQUE,
    title       text NOT NULL,
    body_md     text NOT NULL
);

CREATE TABLE integrations (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider    text NOT NULL,
    endpoint    text NOT NULL,
    api_key     text NOT NULL,
    notes       text
);

CREATE TABLE quotes (
    id              text PRIMARY KEY,
    created_at      timestamptz NOT NULL,
    vehicle_id      text NOT NULL REFERENCES inventory_vehicles(id),
    customer_email  text NOT NULL,
    discount_pct    numeric(5,2) NOT NULL,
    final_price     integer NOT NULL,
    created_via     text NOT NULL,              -- web_chat | staff | mcp
    status          text NOT NULL,              -- open | sold | expired
    note            text,
    seller_name     text,
    sold_at         timestamptz
);

CREATE TABLE price_changes (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts              timestamptz NOT NULL,
    vehicle_id      text NOT NULL REFERENCES inventory_vehicles(id),
    old_price       integer NOT NULL,
    new_price       integer NOT NULL,
    actor_user_id   integer REFERENCES users(id),
    via             text NOT NULL               -- staff | mcp
);

CREATE TABLE reservations (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            text NOT NULL UNIQUE,
    created_at      timestamptz NOT NULL,
    vehicle_id      text NOT NULL REFERENCES inventory_vehicles(id),
    customer_id     integer NOT NULL REFERENCES users(id),
    deposit_amount  integer NOT NULL,
    status          text NOT NULL,              -- pending | confirmed | cancelled
    sinpe_ref       text
);

CREATE TABLE chat_sessions (
    id          text PRIMARY KEY,
    started_at  timestamptz NOT NULL,
    src_ip      text NOT NULL,
    user_agent  text NOT NULL,
    user_id     integer REFERENCES users(id),
    role        text NOT NULL                   -- visitor | customer | staff
);

CREATE TABLE chat_messages (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  text NOT NULL REFERENCES chat_sessions(id),
    ts          timestamptz NOT NULL,
    role        text NOT NULL,                  -- user | assistant
    content     text NOT NULL
);
CREATE INDEX chat_messages_session_idx ON chat_messages (session_id, ts);

CREATE TABLE conversation_index_flags (
    session_id      text PRIMARY KEY REFERENCES chat_sessions(id),
    flagged_at      timestamptz NOT NULL,
    flagged_by_ip   text
);

CREATE TABLE assistant_actions (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts              timestamptz NOT NULL,
    source          text NOT NULL,              -- web_chat | mcp | staff | web
    session_id      text REFERENCES chat_sessions(id),
    actor_user_id   integer REFERENCES users(id),
    action          text NOT NULL,
    params          jsonb NOT NULL,
    status          text NOT NULL,
    result_summary  text
);

CREATE TABLE outbox (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                  timestamptz NOT NULL,
    sender              text NOT NULL,
    recipient           text NOT NULL,
    subject             text NOT NULL,
    body                text NOT NULL,
    source_action_id    integer REFERENCES assistant_actions(id)
);

CREATE TABLE audit_log (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_naive        timestamp,
    event           text NOT NULL,
    detail          text,
    subject_text    text
);

CREATE TABLE web_sessions (
    token       text PRIMARY KEY,
    user_id     integer REFERENCES users(id),
    role        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rag_chunks (
    id              bigserial PRIMARY KEY,
    source_type     text NOT NULL,              -- inventory | bulletin | faq | service_record | conversation | internal_policy
    source_id       text NOT NULL,
    owner_user_id   integer,
    plate           text,
    title           text NOT NULL,
    content         text NOT NULL,
    metadata        jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamptz NOT NULL DEFAULT now(),
    embedding       vector(:EMBED_DIM)
);

CREATE TABLE index_jobs (
    source_type     text NOT NULL,
    source_id       text NOT NULL,
    status          text NOT NULL,              -- pending | done | error
    chunks          integer NOT NULL DEFAULT 0,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source_type, source_id)
);
